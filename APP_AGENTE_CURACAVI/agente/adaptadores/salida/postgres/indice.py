"""Memoria semántica · ADAPTADOR DOCKER: PostgreSQL + pgvector + búsqueda de texto completo.

Implementa el mismo puerto que IndiceChroma (BuscadorFuentes). Cada fragmento es una fila con:
- embedding vector(384): similitud coseno con el operador <=> de pgvector (índice HNSW);
- tsv tsvector: columna generada con to_tsvector('spanish', ...) e índice GIN, que reemplaza a BM25
  para la parte "por palabras" de la búsqueda híbrida (con raíces en español: renovar/renovación).

La fusión (RRF, umbral por índice, prioridad por trámite) es la misma de Chroma:
agente/adaptadores/salida/memoria/busqueda_hibrida.py.

Hay una tabla por proveedor de embeddings (fragmentos_local / fragmentos_offline): vectores de
modelos distintos no se pueden comparar entre sí.
"""
import json

from langchain_core.embeddings import Embeddings

from agente.dominio.texto import STOPWORDS, normalizar
from agente.adaptadores.salida.memoria.busqueda_hibrida import fusionar
from agente.adaptadores.salida.postgres.conexion import pool
from agente.configuracion import settings


def _vector(valores: list[float]) -> str:
    """Formato de texto que entiende pgvector: '[0.1,0.2,...]'."""
    return "[" + ",".join(f"{v:.6f}" for v in valores) + "]"


class IndicePgvector:
    def __init__(self, url: str, embeddings: Embeddings, umbrales: dict | None = None, tabla: str = "fragmentos_local"):
        self.url = url
        self.embeddings = embeddings
        self.umbrales = umbrales or settings.umbrales()
        self.tabla = tabla
        self._crear_tabla()

    def _crear_tabla(self) -> None:
        t, dim = self.tabla, settings.EMBEDDING_DIM
        with pool(self.url).connection() as conn:
            conn.execute("CREATE EXTENSION IF NOT EXISTS vector")
            conn.execute(f"""
                CREATE TABLE IF NOT EXISTS {t} (
                    orden BIGINT GENERATED BY DEFAULT AS IDENTITY,
                    id TEXT PRIMARY KEY,
                    coleccion TEXT NOT NULL,
                    contenido TEXT NOT NULL,
                    metadata JSONB NOT NULL,
                    texto_normalizado TEXT NOT NULL,
                    tsv tsvector GENERATED ALWAYS AS (to_tsvector('spanish', texto_normalizado)) STORED,
                    embedding vector({dim}) NOT NULL)""")
            conn.execute(f"CREATE INDEX IF NOT EXISTS {t}_coleccion ON {t} (coleccion)")
            conn.execute(f"CREATE INDEX IF NOT EXISTS {t}_tsv ON {t} USING GIN (tsv)")
            conn.execute(f"CREATE INDEX IF NOT EXISTS {t}_hnsw ON {t} USING hnsw (embedding vector_cosine_ops)")

    # --- persistencia ---------------------------------------------------------------------
    def _insertar(self, conn, coleccion: str, filas: list[dict]) -> None:
        vectores = self.embeddings.embed_documents([f["texto"] for f in filas])
        conn.cursor().executemany(
            f"""INSERT INTO {self.tabla} (id, coleccion, contenido, metadata, texto_normalizado, embedding)
                VALUES (%s, %s, %s, %s, %s, %s::vector)
                ON CONFLICT (id) DO UPDATE SET contenido = EXCLUDED.contenido, metadata = EXCLUDED.metadata,
                    texto_normalizado = EXCLUDED.texto_normalizado, embedding = EXCLUDED.embedding""",
            [(f["id"], coleccion, f["texto"], json.dumps(f["metadata"], ensure_ascii=False), normalizar(f["texto"]),
              _vector(v)) for f, v in zip(filas, vectores)])

    def construir(self, colecciones: dict[str, list], lote: int = 64) -> dict[str, int]:
        """(Re)crea las colecciones indicadas. Devuelve cuántos fragmentos quedó en cada una."""
        resumen = {}
        for coleccion, docs in colecciones.items():
            filas = [{"id": d.metadata["chunk_id"], "texto": d.page_content,
                      "metadata": {k: v for k, v in d.metadata.items() if v is not None}} for d in docs]
            with pool(self.url).connection() as conn:
                conn.execute(f"DELETE FROM {self.tabla} WHERE coleccion = %s", (coleccion,))
                for i in range(0, len(filas), lote):
                    self._insertar(conn, coleccion, filas[i:i + lote])
            resumen[coleccion] = len(filas)
        return resumen

    def agregar(self, coleccion: str, texto: str, metadata: dict) -> str:
        """Agrega un fragmento (se usa para guardar casos resueltos: memoria episódica)."""
        with pool(self.url).connection() as conn:
            n = conn.execute(f"SELECT count(*) AS n FROM {self.tabla} WHERE coleccion = %s", (coleccion,)).fetchone()["n"]
            chunk_id = metadata.get("chunk_id") or f"{coleccion}:{n}"
            self._insertar(conn, coleccion, [{"id": chunk_id, "texto": texto,
                                              "metadata": {**metadata, "chunk_id": chunk_id, "coleccion": coleccion}}])
        return chunk_id

    def corpus(self, coleccion: str) -> list[dict]:
        with pool(self.url).connection() as conn:
            filas = conn.execute(f"SELECT id, contenido, metadata FROM {self.tabla} WHERE coleccion = %s ORDER BY orden",
                                 (coleccion,)).fetchall()
        return [{"id": f["id"], "texto": f["contenido"], "metadata": f["metadata"]} for f in filas]

    def conteo(self) -> dict[str, int]:
        with pool(self.url).connection() as conn:
            filas = conn.execute(f"SELECT coleccion, count(*) AS n FROM {self.tabla} GROUP BY coleccion").fetchall()
        return {f["coleccion"]: f["n"] for f in filas}

    # --- búsqueda ---------------------------------------------------------------------------
    @staticmethod
    def _consulta_texto(consulta: str) -> str:
        """Consulta OR para to_tsquery: 'renovar | permiso | circulacion' (sin palabras vacías)."""
        import re

        palabras = [p for p in re.findall(r"[a-z0-9]+", normalizar(consulta)) if p not in STOPWORDS and len(p) > 1]
        return " | ".join(dict.fromkeys(palabras))

    def buscar(self, coleccion: str, consulta: str, k: int = settings.TOP_K, tramite: str | None = None,
               hibrida: bool = True, umbral: float | None = None, boost: bool = True) -> list[dict]:
        """Búsqueda híbrida con umbral. Devuelve hasta k fragmentos ordenados por relevancia."""
        if not consulta.strip():
            return []
        umbral = self.umbrales.get(coleccion, 0.4) if umbral is None else umbral
        candidatos = k * 3
        vector = _vector(self.embeddings.embed_query(consulta))
        with pool(self.url).connection() as conn:
            # ef_search alto: con pocos miles de fragmentos, HNSW entrega prácticamente el resultado exacto.
            conn.execute("SET LOCAL hnsw.ef_search = 1000")
            vecinos = conn.execute(
                f"""SELECT id, contenido, metadata, 1 - (embedding <=> %s::vector) AS similitud FROM {self.tabla}
                    WHERE coleccion = %s ORDER BY embedding <=> %s::vector LIMIT %s""",
                (vector, coleccion, vector, candidatos)).fetchall()
            por_texto = []
            terminos = self._consulta_texto(consulta)
            if hibrida and terminos:
                por_texto = conn.execute(
                    f"""SELECT id, contenido, metadata FROM {self.tabla}, to_tsquery('spanish', %s) AS q
                        WHERE coleccion = %s AND tsv @@ q ORDER BY ts_rank(tsv, q) DESC, orden LIMIT %s""",
                    (terminos, coleccion, candidatos)).fetchall()
        if not vecinos and not por_texto:
            return []
        filas_por_id = {f["id"]: {"texto": f["contenido"], "metadata": f["metadata"]} for f in vecinos + por_texto}
        return fusionar(coleccion, consulta, filas_por_id, [(f["id"], float(f["similitud"])) for f in vecinos],
                        [f["id"] for f in por_texto], k, umbral, tramite, boost)
