"""Registro municipal · ADAPTADOR DOCKER (PostgreSQL).

Hereda toda la lógica SQL de RegistroSQL (adaptadores/salida/memoria/registro_sql.py); aquí solo cambia cómo se
conecta, cómo se marcan los parámetros (%s) y cómo se recrea el esquema. Por eso las pruebas de
contrato (tests/integracion/) corren la misma batería contra SQLite y contra PostgreSQL.

Concurrencia: reservar_cupo es un UPDATE condicionado (WHERE estado = 'disponible'). En PostgreSQL
la fila queda bloqueada durante la actualización, así que si dos atenciones piden la misma hora al
mismo tiempo, solo una la obtiene.
"""
from contextlib import contextmanager

from agente.adaptadores.salida.memoria.registro_sql import TABLAS, RegistroSQL, esquema
from agente.adaptadores.salida.postgres.conexion import pool


class RegistroPostgres(RegistroSQL):
    MARCADOR = "%s"

    def __init__(self, url: str):
        self.url = url

    @contextmanager
    def _conectar(self):
        with pool(self.url).connection() as conn:
            yield conn

    def _recrear_esquema(self, conn) -> None:
        conn.execute(f"DROP TABLE IF EXISTS {', '.join(TABLAS)} CASCADE")
        conn.execute(esquema("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"))

    def existe(self) -> bool:
        return bool(self._filas("SELECT 1 FROM information_schema.tables WHERE table_name = 'solicitudes'"))
